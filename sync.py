#!/usr/bin/env python3
"""Publish canonical agent rules and shared documentation to configured projects."""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


SOURCE_ROOT = Path(__file__).resolve().parent
WORKSPACE_ROOT = SOURCE_ROOT.parent
if WORKSPACE_ROOT.name == "projects":
	# Use this workspace when project repositories are siblings of the rules repo.
	DEFAULT_PROJECTS_ROOT = WORKSPACE_ROOT
else:
	# Support workspaces that contain project repositories in a projects folder.
	DEFAULT_PROJECTS_ROOT = WORKSPACE_ROOT / "projects"
WORKSPACE_PROJECTS_ROOT = Path(os.environ.get("WORKSPACE_PROJECTS_ROOT", DEFAULT_PROJECTS_ROOT))
TARGETS_FILE = SOURCE_ROOT / "local" / "targets.tsv"
TASK_DOCS_README_SOURCE = SOURCE_ROOT / "templates" / "task-docs-readme.md"
AGENT_GENERATOR_SOURCE = SOURCE_ROOT / "templates" / "gen-agent-rules.py"
SPECS_README_SOURCE = SOURCE_ROOT / "shared" / "specs" / "README.md"
ENTRYPOINTS = ("AGENTS.md", "CLAUDE.md", "GEMINI.md")
START_MARKER = "<!-- BEGIN SHARED TASK DOC RULES -->"
END_MARKER = "<!-- END SHARED TASK DOC RULES -->"


def validate_sources() -> None:
	"""Check the canonical inputs before modifying any targets."""
	sources = (
		(SOURCE_ROOT / "shared" / "base.md", "shared rules or local/targets.tsv are missing"),
		(TARGETS_FILE, "source rules or targets.tsv are missing"),
		(TASK_DOCS_README_SOURCE, "task docs README source is missing"),
		(AGENT_GENERATOR_SOURCE, "agent generator template is missing"),
		(SPECS_README_SOURCE, "spec docs README source is missing"),
	)
	# Report the first missing input and stop before any target is changed.
	for path, message in sources:
		if not path.is_file():
			print(f"---> {message}: {path}", file=sys.stderr)
			raise SystemExit(2)


def render_workspace_instructions(framework_source: Path) -> str:
	"""Render shared rules and the configured framework for the projects root."""
	parts = []
	for source in (SOURCE_ROOT / "shared" / "base.md", framework_source):
		body = source.read_text(encoding="utf-8").rstrip()
		if body:
			name = source.relative_to(SOURCE_ROOT).as_posix()
			parts.append(f"<!-- BEGIN SOURCE: {name} -->\n\n{body}\n\n<!-- END SOURCE: {name} -->")
	return ("<!-- GENERATED BY agent-rules. Do not edit this file directly. -->\n\n"
		+ "\n\n".join(parts) + "\n")


def sync_workspace_root(framework_source: Path, check: bool = False) -> None:
	"""Generate only the three entrypoints for a target at the projects root."""
	if not WORKSPACE_PROJECTS_ROOT.is_dir():
		raise FileNotFoundError(f"projects root is missing: {WORKSPACE_PROJECTS_ROOT}")
	override = WORKSPACE_PROJECTS_ROOT / "AGENTS.override.md"
	if override.is_file() and override.read_text(encoding="utf-8").strip():
		raise ValueError(f"{override} hides generated AGENTS.md; move its rules into "
			"shared/base.md or the configured framework rules before generating")
	content = render_workspace_instructions(framework_source).encode("utf-8")
	if check:
		stale = [name for name in ENTRYPOINTS
			if not (WORKSPACE_PROJECTS_ROOT / name).is_file()
			or (WORKSPACE_PROJECTS_ROOT / name).read_bytes() != content]
		if stale:
			raise ValueError(f"projects root: missing or stale: {', '.join(stale)}; run sync.py")
		print("---> checked projects root entrypoints")
		return
	for entrypoint in ENTRYPOINTS:
		output = WORKSPACE_PROJECTS_ROOT / entrypoint
		temp_path: Path | None = None
		try:
			with tempfile.NamedTemporaryFile(
				mode="wb",
				dir=WORKSPACE_PROJECTS_ROOT,
				delete=False,
			) as temp_file:
				temp_path = Path(temp_file.name)
				temp_file.write(content)
			os.replace(temp_path, output)
		finally:
			if temp_path is not None and temp_path.exists():
				temp_path.unlink()
	print("---> generated workspace root AGENTS.md, CLAUDE.md, and GEMINI.md")


def read_targets() -> list[tuple[str, str]]:
	"""Load target and framework pairs from the pipe-delimited target map."""
	targets: list[tuple[str, str]] = []
	with TARGETS_FILE.open(encoding="utf-8") as target_file:
		# Ignore blank and comment lines in the target map.
		for line_number, raw_line in enumerate(target_file, start=1):
			line = raw_line.strip()
			if not line or line.startswith("#"):
				continue
			fields = [field.strip() for field in line.split("|")]
			if len(fields) != 2 or not all(fields):
				print(f"---> invalid target mapping at {TARGETS_FILE}:{line_number}", file=sys.stderr)
				raise SystemExit(2)
			targets.append((fields[0], fields[1]))
	return targets


def render_task_docs_readme(readme: Path) -> str:
	"""Validate managed boundaries before any target files are changed."""
	content = readme.read_text(encoding="utf-8") if readme.is_file() else "# Documentation\n"
	lines = content.splitlines()

	kept_lines: list[str] = []
	inside_block = False
	# Remove all prior managed blocks while keeping lines outside them.
	for line in lines:
		if line == START_MARKER:
			if inside_block:
				raise ValueError(f"nested shared task docs markers: {readme}")
			inside_block = True
			continue
		if line == END_MARKER:
			if not inside_block:
				raise ValueError(f"unmatched shared task docs end marker: {readme}")
			inside_block = False
			continue
		if not inside_block:
			kept_lines.append(line)
	if inside_block:
		raise ValueError(f"shared task docs markers are incomplete: {readme}")
	while kept_lines and not kept_lines[-1]:
		kept_lines.pop()

	shared_content = TASK_DOCS_README_SOURCE.read_text(encoding="utf-8").rstrip("\r\n")
	updated = "\n".join(kept_lines)
	updated += f"\n\n{START_MARKER}\n\n{shared_content}\n{END_MARKER}\n"
	return updated


def sync_task_docs_readme(target_dir: Path, updated: str) -> None:
	"""Write the validated documentation index without changing local content."""
	readme = target_dir / "docs" / "README.md"
	readme.parent.mkdir(parents=True, exist_ok=True)
	temp_path: Path | None = None
	try:
		# Replace the index atomically after the complete managed section is ready.
		with tempfile.NamedTemporaryFile(
			mode="w",
			encoding="utf-8",
			newline="\n",
			dir=readme.parent,
			delete=False,
		) as temp_file:
			temp_path = Path(temp_file.name)
			temp_file.write(updated)
		os.replace(temp_path, readme)
	finally:
		# Remove the temporary file if writing or replacement failed.
		if temp_path is not None and temp_path.exists():
			temp_path.unlink()


def process_target(relative_target: str, framework_name: str, check: bool = False) -> None:
	"""Publish the shared rule files and documentation for one target."""
	target_dir = WORKSPACE_PROJECTS_ROOT / relative_target
	framework_file = SOURCE_ROOT / "shared" / "frameworks" / f"{framework_name}.md"
	if not target_dir.is_dir():
		# Report configured targets that are absent from this workspace.
		raise FileNotFoundError(f"target is missing: {relative_target}")
	if not framework_file.is_file():
		# Report framework names that have no canonical source file.
		raise FileNotFoundError(f"framework is missing: {framework_name}")
	if Path(relative_target) == Path("."):
		sync_workspace_root(framework_file, check=check)
		return
	override = target_dir / "AGENTS.override.md"
	if override.is_file() and override.read_text(encoding="utf-8").strip():
		raise ValueError(f"{override} hides generated AGENTS.md; move its rules into "
			".agent-rules/project.md and remove the override before sync")

	rules_dir = target_dir / ".agent-rules"
	scripts_dir = target_dir / "scripts"
	if check:
		pairs = (
			(SOURCE_ROOT / "shared" / "base.md", rules_dir / "base.md"),
			(framework_file, rules_dir / "framework.md"),
			(AGENT_GENERATOR_SOURCE, scripts_dir / "gen-agent-rules.py"),
			(SPECS_README_SOURCE, target_dir / "docs" / "specs" / "README.md"),
		)
		stale = [str(dest.relative_to(target_dir)) for source, dest in pairs
			if not dest.is_file() or source.read_bytes() != dest.read_bytes()]
		readme = target_dir / "docs" / "README.md"
		content = readme.read_text(encoding="utf-8") if readme.is_file() else ""
		shared = TASK_DOCS_README_SOURCE.read_text(encoding="utf-8").rstrip("\r\n")
		block = f"{START_MARKER}\n\n{shared}\n{END_MARKER}"
		if (block not in content or content.splitlines().count(START_MARKER) != 1
			or content.splitlines().count(END_MARKER) != 1):
			stale.append("docs/README.md (managed block)")
		if stale:
			raise ValueError(f"{relative_target}: missing or stale: {', '.join(stale)}; run sync.py")
		subprocess.run([sys.executable, str(scripts_dir / "gen-agent-rules.py"), "--check"],
			cwd=target_dir, check=True)
		print(f"---> checked {relative_target}")
		return
	updated_readme = render_task_docs_readme(target_dir / "docs" / "README.md")
	rules_dir.mkdir(parents=True, exist_ok=True)
	scripts_dir.mkdir(parents=True, exist_ok=True)
	(target_dir / "docs" / "specs").mkdir(parents=True, exist_ok=True)
	# Copy canonical shared rules, documentation, and the local generator.
	shutil.copyfile(SOURCE_ROOT / "shared" / "base.md", rules_dir / "base.md")
	shutil.copyfile(framework_file, rules_dir / "framework.md")
	generator = scripts_dir / "gen-agent-rules.py"
	shutil.copyfile(AGENT_GENERATOR_SOURCE, generator)
	generator.chmod(generator.stat().st_mode | 0o111)
	sync_task_docs_readme(target_dir, updated_readme)
	shutil.copyfile(SPECS_README_SOURCE, target_dir / "docs" / "specs" / "README.md")
	print(f"---> updated shared rules for {relative_target}")
	# Regenerate the target's agent files after all source rules are current.
	subprocess.run([sys.executable, str(generator)], cwd=target_dir, check=True)


def main() -> int:
	"""Validate canonical inputs and publish them to every configured target."""
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--check", action="store_true", help="Check outputs without writing")
	args = parser.parse_args()
	validate_sources()
	targets = read_targets()
	failed = False
	# Continue publishing other targets after reporting an individual failure.
	for relative_target, framework_name in targets:
		try:
			process_target(relative_target, framework_name, check=args.check)
		except (OSError, ValueError, subprocess.CalledProcessError) as error:
			print(f"---> {error}", file=sys.stderr)
			failed = True
	return 1 if failed else 0


if __name__ == "__main__":
	# Return the sync result as the process exit status.
	raise SystemExit(main())
