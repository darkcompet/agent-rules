#!/usr/bin/env python3
"""Generate agent instruction files from this project's local rule sources."""

from __future__ import annotations

import argparse
import os
import sys
import tempfile
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parent.parent
RULES_DIR = PROJECT_ROOT / ".agent-rules"
ENTRYPOINTS = ("AGENTS.md", "CLAUDE.md", "GEMINI.md")


def generate(check: bool = False) -> None:
	"""Write the combined shared and project rules to each agent entrypoint."""
	override = PROJECT_ROOT / "AGENTS.override.md"
	if override.is_file() and override.read_text(encoding="utf-8").strip():
		raise ValueError(
			f"{override} hides generated AGENTS.md in Codex; move its rules into "
			".agent-rules/project.md and remove the override before generating"
		)
	sources = (RULES_DIR / "base.md", RULES_DIR / "framework.md")
	for source in sources:
		if not source.is_file():
			raise FileNotFoundError(f"required rules file is missing: {source}")

	inputs = list(sources)
	project_rules = RULES_DIR / "project.md"
	if project_rules.is_file():
		inputs.append(project_rules)
	parts = []
	for source in inputs:
		body = source.read_text(encoding="utf-8").rstrip()
		if body:
			name = source.relative_to(PROJECT_ROOT).as_posix()
			parts.append(f"<!-- BEGIN SOURCE: {name} -->\n\n{body}\n\n<!-- END SOURCE: {name} -->")

	content = "<!-- GENERATED BY agent-rules. Do not edit this file directly. -->\n\n"
	content += "\n\n".join(part for part in parts if part) + "\n"
	if len(content.encode("utf-8")) >= 32768:
		print("warning: generated instructions reach Codex's default 32 KiB limit; "
			"also check ancestor instructions and project_doc_max_bytes", file=sys.stderr)
	if check:
		stale = [name for name in ENTRYPOINTS
			if not (PROJECT_ROOT / name).is_file()
			or (PROJECT_ROOT / name).read_bytes() != content.encode("utf-8")]
		if stale:
			raise ValueError(f"generated instructions missing or stale: {', '.join(stale)}; run the generator")
		print("---> generated instructions are current")
		return
	for entrypoint in ENTRYPOINTS:
		output = PROJECT_ROOT / entrypoint
		temp_path: Path | None = None
		try:
			with tempfile.NamedTemporaryFile(
				mode="w",
				encoding="utf-8",
				newline="\n",
				dir=PROJECT_ROOT,
				delete=False,
			) as temp_file:
				temp_path = Path(temp_file.name)
				temp_file.write(content)
			os.replace(temp_path, output)
		finally:
			if temp_path is not None and temp_path.exists():
				temp_path.unlink()

	print("---> generated AGENTS.md, CLAUDE.md, and GEMINI.md")


if __name__ == "__main__":
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("--check", action="store_true", help="Check generated files without writing")
	args = parser.parse_args()
	try:
		generate(check=args.check)
	except (OSError, ValueError) as error:
		print(f"---> {error}", file=sys.stderr)
		raise SystemExit(1)
