#!/usr/bin/env python3
"""Generate agent instruction files from this project's local rule sources."""

from __future__ import annotations

import os
import sys
import tempfile
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parent.parent
RULES_DIR = PROJECT_ROOT / ".agent-rules"
ENTRYPOINTS = ("AGENTS.md", "CLAUDE.md", "GEMINI.md")


def generate() -> None:
	"""Write the combined shared and project rules to each agent entrypoint."""
	sources = (RULES_DIR / "base.md", RULES_DIR / "framework.md")
	for source in sources:
		if not source.is_file():
			raise FileNotFoundError(f"required rules file is missing: {source}")

	parts = [source.read_text(encoding="utf-8").rstrip() for source in sources]
	project_rules = RULES_DIR / "project.md"
	if project_rules.is_file():
		parts.append(project_rules.read_text(encoding="utf-8").rstrip())

	content = "<!-- GENERATED BY agent-rules. Do not edit this file directly. -->\n\n"
	content += "\n\n".join(part for part in parts if part) + "\n"
	for entrypoint in ENTRYPOINTS:
		output = PROJECT_ROOT / entrypoint
		temp_path: Path | None = None
		try:
			with tempfile.NamedTemporaryFile(
				mode="w",
				encoding="utf-8",
				newline="\n",
				dir=PROJECT_ROOT,
				delete=False,
			) as temp_file:
				temp_path = Path(temp_file.name)
				temp_file.write(content)
			os.replace(temp_path, output)
		finally:
			if temp_path is not None and temp_path.exists():
				temp_path.unlink()

	print("---> generated AGENTS.md, CLAUDE.md, and GEMINI.md")


if __name__ == "__main__":
	try:
		generate()
	except OSError as error:
		print(f"---> {error}", file=sys.stderr)
		raise SystemExit(1)
